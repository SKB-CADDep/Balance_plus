"""
Скрипт первичного заполнения базы данных (Database Bootstrapping / Seeding).

Используется на этапе развертывания приложения (deployment) или при настройке 
локального окружения для заполнения пустой базы данных необходимыми 
базовыми справочниками и эталонными значениями (через функцию init_db).
"""

import logging

from sqlmodel import Session

from app.core.database import engine, init_db


logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)


# [ENGINEERING CONTEXT]
# Почему заполнение данных вынесено в отдельный скрипт, а не в миграции базы (Alembic):
# Это классический паттерн разделения ответственности (Separation of Concerns). 
# Миграции (Alembic) отвечают строго за структуру таблиц (DDL: CREATE, ALTER). 
# Скрипты инициализации отвечают за наполнение бизнес-данными (DML: INSERT, UPDATE).
# Такое разделение позволяет легко очищать и пересоздавать тестовые базы данных с нуля 
# или обновлять справочники, не ломая при этом жесткую хронологическую историю миграций.
def init() -> None:
    """
    Инициализирует подключение к базе данных и запускает процесс заполнения.
    
    Создает контекст сессии SQLModel и делегирует выполнение 
    бизнес-логики функции `init_db()`.
    """
    with Session(engine):
        init_db()


def main() -> None:
    """
    Главная точка входа. Оборачивает процесс инициализации базовым логированием 
    для удобства отслеживания прогресса в консоли или логах Docker-контейнера.
    """
    logger.info("Creating initial data")
    init()
    logger.info("Initial data created")


if __name__ == "__main__":
    main()
    
"""
Внедрение зависимостей (Dependency Injection) для FastAPI.

Этот модуль содержит переиспользуемые зависимости (провайдеры ресурсов), 
которые FastAPI автоматически внедряет в эндпоинты (роутеры) при каждом 
входящем HTTP-запросе. Обеспечивает безопасное управление жизненным 
циклом системных ресурсов.
"""

from app.core.database import SessionLocal


def get_db():
    """
    Создает и управляет сессией подключения к базе данных для одного HTTP-запроса.

    [ENGINEERING CONTEXT]
    Почему используется `yield` и блок `try/finally`, а не обычный `return`:
    Когда в эндпоинт приходит HTTP-запрос, FastAPI запускает эту функцию. 
    Она доходит до `yield db`, отдает сессию в роутер и "замораживается". 
    Как только роутер отправил ответ пользователю (или даже если эндпоинт упал с ошибкой 500), 
    FastAPI возвращается в эту функцию и гарантированно выполняет блок `finally: db.close()`. 
    Это критически важно: если не закрывать сессию, соединения с БД не вернутся 
    в пул (Connection Pool), и при нагрузке приложение быстро упадет из-за "утечки соединений".

    Yields:
        sqlalchemy.orm.Session: Активная сессия для транзакций с базой данных.
    """
    db = SessionLocal()
    try:
        yield db
    finally:
        db.close()
        
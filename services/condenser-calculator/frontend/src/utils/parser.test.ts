import { describe, expect, it } from 'vitest';
import { parseRange } from './parser';

describe('parseRange', () => {
  describe('Формат 1: Список чисел, разделенных пробелами или запятыми', () => {
    it('должен корректно распарсить список чисел, разделенный запятыми', () => {
      expect(parseRange('10, 20, 30')).toEqual([10, 20, 30]);
      expect(parseRange('10,20,30')).toEqual([10, 20, 30]);
    });

    it('должен корректно распарсить список чисел, разделенный пробелами', () => {
      expect(parseRange('10 20 30')).toEqual([10, 20, 30]);
      expect(parseRange('10   20   30')).toEqual([10, 20, 30]);
    });

    it('должен обрабатывать смешанные разделители и игнорировать нечисловые элементы', () => {
      expect(parseRange('10, 20 30, 40')).toEqual([10, 20, 30, 40]);
      expect(parseRange('10, abc, 30')).toEqual([10, 30]);
    });
  });

  describe('Формат 2: Диапазон с шагом (start-end-step)', () => {
    it('должен сформировать возрастающий диапазон с заданным шагом (например, 10-50-5)', () => {
      expect(parseRange('10-50-5')).toEqual([10, 15, 20, 25, 30, 35, 40, 45, 50]);
    });

    it('должен сформировать убывающий диапазон с заданным шагом (например, 50-10-10)', () => {
      expect(parseRange('50-10-10')).toEqual([50, 40, 30, 20, 10]);
    });

    it('должен правильно обрабатывать дробные значения и шаг', () => {
      expect(parseRange('1.5-3.0-0.5')).toEqual([1.5, 2.0, 2.5, 3.0]);
    });

    it('должен возвращать пустой массив при невалидном шаге (step <= 0)', () => {
      expect(parseRange('10-50-0')).toEqual([]);
    });
  });

  describe('Формат 3: Диапазон с количеством точек (start-end:count)', () => {
    it('должен сгенерировать точное количество элементов в диапазоне', () => {
      expect(parseRange('10-50:5')).toEqual([10, 20, 30, 40, 50]);
    });

    it('должен поддерживать отрицательную динамику с количеством элементов', () => {
      expect(parseRange('100-0:5')).toEqual([100, 75, 50, 25, 0]);
    });

    it('должен возвращать пустой массив при count < 2', () => {
      expect(parseRange('10-50:1')).toEqual([]);
      expect(parseRange('10-50:0')).toEqual([]);
    });
  });

  describe('Формат 4: Стандартный диапазон без шага (start-end) и одиночные числа', () => {
    it('должен генерировать последовательные целые числа с шагом 1', () => {
      expect(parseRange('1-5')).toEqual([1, 2, 3, 4, 5]);
      expect(parseRange('5-1')).toEqual([5, 4, 3, 2, 1]);
    });

    it('должен распарсить одно целое или дробное число', () => {
      expect(parseRange('42')).toEqual([42]);
      expect(parseRange('12.34')).toEqual([12.34]);
    });
  });

  describe('Негативные сценарии и граничные условия', () => {
    it('должен возвращать пустой массив для пустой строки или пробелов', () => {
      expect(parseRange('')).toEqual([]);
      expect(parseRange('   ')).toEqual([]);
    });

    it('должен возвращать пустой массив для совершенно невалидных строк', () => {
      expect(parseRange('invalid-range')).toEqual([]);
      expect(parseRange('---')).toEqual([]);
      expect(parseRange('hello world')).toEqual([]);
    });
  });
});
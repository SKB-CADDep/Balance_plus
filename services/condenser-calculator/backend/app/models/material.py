"""
ORM-модель для таблицы материалов.

Описывает схему хранения справочника трубных материалов в базе данных PostgreSQL. 
Материалы используются для определения коэффициентов теплопроводности (λ) 
при тепловом расчете конденсаторов. Реализует связь Many-to-Many 
с таблицей конденсаторов.
"""

from sqlalchemy import Column, Integer, String, JSON, text
from sqlalchemy.orm import relationship

from app.models.base import Base


class Material(Base):
    """
    Модель базы данных для сущности "Материал трубок".
    
    Содержит физические свойства металлов/сплавов (например, Л68, МНЖ, титан) 
    и их уникальные идентификаторы для связи с другими микросервисами.
    """
    __tablename__ = "materials"

    # Суррогатный первичный ключ (для внутренних связей БД)
    id = Column(Integer, primary_key=True, autoincrement=True)
    
    # Глобальный уникальный идентификатор (для интеграции с внешними системами и PDM)
    material_uuid = Column(String, unique=True, index=True, nullable=False)
    
    # Общепринятое наименование или марка сплава (например, "12Х18Н10Т")
    name = Column(String, nullable=False, unique=True)

    # Массив точек температурной зависимости теплопроводности λ = f(t).
    # Формат JSON: [[t1, λ1], [t2, λ2], ...], где t - °C, λ - Вт/(м·К)
    # Используется математическим ядром для генерации сплайнов/интерполяторов.
    thermal_conductivity_points = Column(JSON, nullable=False)

    # Резервное поле для хранения полной физической спецификации материала 
    # (плотность, модуль Юнга, предел текучести и т.д.) в виде свободного JSON.
    # Заложено для расширения функционала ядра в будущих релизах.
    full_properties = Column(JSON)

    # Двунаправленная связь "Многие-ко-Многим" (Many-to-Many) с таблицей конденсаторов.
    # Показывает, в каких моделях аппаратов физически может применяться данный материал.
    # Связь осуществляется через промежуточную (association) таблицу.
    condensers = relationship(
        "Condenser", 
        secondary="condenser_material_association", 
        back_populates="materials"
    )
    
"""
Инициализация и настройка глобального конвертера физических величин.

Модуль создает единый (Singleton) экземпляр `UnitConverter` для всего микросервиса.
При запуске приложения проверяет наличие необходимых для термодинамических расчетов 
величин (например, энтальпии) и динамически регистрирует их в случае отсутствия.
"""

import logging
from app.utils.uniconv import UnitConverter

logger = logging.getLogger(__name__)

# Создание глобального экземпляра конвертера.
# Остальные модули приложения (адаптеры, роутеры) должны импортировать `converter` именно отсюда.
converter = UnitConverter()

# Проверяем, зарегистрирован ли параметр энтальпии в базовой комплектации конвертера.
# Если нет (перехват исключения UnknownParameterError), добавляем его динамически.
try:
    converter.get_available_units("enthalpy")
except Exception:
    logger.info("Добавляем параметр 'enthalpy' в глобальный конвертер")

    # Регистрация новой физической величины с базовой единицей в системе СИ (кДж/кг)
    converter.add_parameter(
        parameter_type="enthalpy",
        base_unit_symbol="кДж/кг",
        base_unit_name="Килоджоуль на килограмм",
    )

    # Добавление исторической единицы измерения (ккал/кг), часто встречающейся в ГОСТах.
    # Коэффициент перевода: 1 ккал = 4.1868 кДж (Международная табличная калория).
    converter.add_unit(
        parameter_type="enthalpy",
        unit_symbol="ккал/кг",
        unit_name="Килокалория на килограмм",
        to_base=4.1868,
        from_base=1 / 4.1868,
    )
    
"""
Базовый модуль определения математической проблемы для решателей уравнений.

Отделяет саму формулу расчета (и её производную) от алгоритмов поиска корней 
(таких как метод Ньютона, дихотомия и др.). Это позволяет гибко менять 
эмпирические коэффициенты или само уравнение, не переписывая логику численных методов.
"""

import math


class ProblemDefinition:
    """
    Инкапсулирует математическую постановку задачи: расчет A3_delt и его производной.
    
    Цель класса — предоставить унифицированный интерфейс (f, df) для поиска 
    корня уравнения F(x) = 0 относительно заданного целевого значения target_delta.
    """

    def __init__(self):
        """
        Инициализирует базовые константы.

        Вычисляет и кэширует множители при создании экземпляра класса
        для максимальной производительности в итерационных циклах. 
        В расчетах используются эмпирические аппроксимации pi и e.
        """
        pi = 3.1415
        e_approx = 2.71
        power = 0.83

        # Вычисление константы C для уравнения A3_delt = 1 - C * X^(power-1)
        self.c = (pi / e_approx) ** power
        self.power_minus_1 = power - 1.0  # Равно -0.17

    def calculate_delta(self, x: float) -> float:
        """
        Рассчитывает значение A3_delt для заданного X.

        Args:
            x (float): Переменная (должна быть строго больше нуля).

        Returns:
            float: Значение A3_delt. Возвращает float('nan'), если x <= 0,
                так как возведение отрицательного числа в дробную степень 
                не определено на множестве действительных чисел.
        """
        if x <= 0:
            return float('nan')
        return 1.0 - self.c * math.pow(x, self.power_minus_1)

    def f(self, x: float, target_delta: float) -> float:
        """
        Целевая функция для численных решателей.

        Корень этой функции мы ищем: F(x) = A3_delt(x) - target_delta = 0.

        Args:
            x (float): Текущее приближение переменной.
            target_delta (float): Искомое (целевое) значение A3_delt.

        Returns:
            float: Невязка (ошибка) текущего приближения.
        """
        return self.calculate_delta(x) - target_delta

    def df(self, x: float) -> float:
        """
        Производная целевой функции F(x) по переменной x.

        Критически важна для градиентных методов оптимизации (например, метода Ньютона-Рафсона), 
        так как определяет направление и шаг следующей итерации.

        Математически:
        d/dx (1 - C * x^p - T) = -C * p * x^(p-1)
        где p = (power - 1) = -0.17

        Args:
            x (float): Текущее приближение переменной.

        Returns:
            float: Значение производной в точке x. Возвращает float('nan') при x <= 0.
        """
        if x <= 0:
            return float('nan')
        return -self.c * self.power_minus_1 * math.pow(x, self.power_minus_1 - 1.0)
"""
Вспомогательный модуль для генерации математических сеток.

Содержит легковесные утилиты для равномерного разбиения числовых диапазонов.
Используется расчетными модулями (например, для генерации шагов при 
построении графиков или создания массивов переменных параметров).
"""

import numpy as np


def split_into_parts(number, n_parts):
    """
    Делит отрезок от 0 до заданного числа на равные интервалы.

    Является удобной оберткой над функцией numpy.linspace. Формирует массив 
    граничных точек (узлов сетки), который всегда включает в себя 0 и 
    верхнюю границу (number).

    Args:
        number (float | int): Верхняя граница диапазона (конечное значение).
        n_parts (int): Требуемое количество интервалов разбиения.

    Returns:
        numpy.ndarray: Одномерный массив из (n_parts + 1) элементов, 
            содержащий координаты узлов с равномерным шагом.
    """
    return np.linspace(0, number, n_parts + 1)
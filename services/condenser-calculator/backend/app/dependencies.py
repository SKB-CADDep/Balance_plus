"""
Модуль инъекции зависимостей (Dependencies) для FastAPI.

Содержит переиспользуемые функции-зависимости, которые подключаются к эндпоинтам 
через параметр `Depends()`. Изолирует логику управления инфраструктурными 
ресурсами (БД, кэш, авторизация) от бизнес-логики маршрутов.
"""

from typing import Generator
from sqlalchemy.orm import Session
from app.core.database import SessionLocal


def get_db() -> Generator[Session, None, None]:
    """
    Управляет жизненным циклом сессии базы данных для HTTP-запроса.

    Функция работает как генератор. FastAPI вызывает её при поступлении запроса,
    получает сессию и передает её в эндпоинт. После завершения запроса 
    (успешного или с ошибкой) выполнение возвращается сюда для очистки ресурсов.

    Yields:
        Session: Объект сессии SQLAlchemy для выполнения транзакций.

    Пример использования:
        @router.get("/condensers")
        def get_all(db: Session = Depends(get_db)):
            ...
    """
    db = SessionLocal()
    try:
        # Передаем сессию в эндпоинт. FastAPI приостановит выполнение
        # этой зависимости, пока HTTP-запрос не будет полностью обработан.
        yield db
    finally:
        # Гарантируем закрытие сессии и возврат соединения в Connection Pool 
        # даже в случае 500-й ошибки или неперехваченного Exception в роутере.
        # Критически важно для предотвращения исчерпания пула соединений БД (Connection Leaks).
        db.close()
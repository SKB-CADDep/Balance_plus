"""
Модуль внедрения зависимостей (Dependency Injection) для FastAPI.

Содержит провайдеры (генераторы) ресурсов, которые переиспользуются в эндпоинтах.
Основная задача модуля — безопасное управление жизненным циклом внешних подключений 
(например, пулом соединений с базой данных), гарантирующее их корректное открытие и закрытие.
"""

from typing import Generator
from app.core.database import SessionLocal

def get_db() -> Generator:
    """
    Провайдер сессии базы данных (SQLAlchemy Session).

    Предназначен для использования в маршрутизаторах через `Depends(get_db)`.
    Функция реализована как генератор, что позволяет разделить её выполнение 
    на две фазы (до обработки HTTP-запроса и после):
    1. Открывает сессию и передает её в роутер (yield).
    2. Ждет завершения обработки запроса клиентом.
    3. Гарантированно закрывает сессию в блоке `finally` (возвращая соединение в пул),
       даже если во время работы API возникли исключения или ошибки.

    Yields:
        Session: Активная сессия подключения к базе данных.
    """
    db = SessionLocal()
    try:
        yield db
    finally:
        db.close()
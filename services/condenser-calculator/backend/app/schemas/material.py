"""
Pydantic-схемы для сущности «Материал труб».

Определяют контракты данных для справочника материалов. Материал трубок 
(например, латунь, нержавеющая сталь, титан) содержит зависимость коэффициента 
теплопроводности от температуры, которая необходима физическому ядру 
для расчета суммарного коэффициента теплопередачи конденсатора.
"""

from pydantic import BaseModel, Field, ConfigDict
from typing import List


class MaterialListItem(BaseModel):
    """
    Краткая схема материала (для списков и селекторов).
    
    Используется для легковесной передачи списка доступных материалов 
    без загрузки тяжелых массивов теплофизических свойств.
    """
    id: int = Field(..., description="Уникальный идентификатор материала в БД")
    name: str = Field(..., description="Название материала или марка сплава (например, 'Л68', '12Х18Н10Т')")

    model_config = ConfigDict(from_attributes=True)


class MaterialDetail(BaseModel):
    """
    Детальная схема материала.
    
    Включает в себя массивы теплофизических свойств. Эта модель 
    передается в слои адаптеров и математики для выполнения 
    расчетов теплопередачи.
    """
    id: int = Field(..., description="Уникальный идентификатор материала")
    name: str = Field(..., description="Название материала или марка сплава")
    
    thermal_conductivity_points: List[List[float]] = Field(
        ...,
        description=(
            "Массив точек для интерполяции зависимости коэффициента теплопроводности "
            "от температуры. Формат: [[t1, λ1], [t2, λ2], ...], где t — температура "
            "стенки (обычно в °C), а λ — теплопроводность (Вт/(м·К) или ккал/(м·ч·°C) "
            "в зависимости от стандарта БД)."
        )
    )

    model_config = ConfigDict(from_attributes=True)

# Алиас для удобного импорта в других модулях
MaterialShort = MaterialListItem
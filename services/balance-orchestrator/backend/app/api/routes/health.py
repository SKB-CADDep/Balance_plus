"""
Роутер проверки состояния микросервиса (Health Check).
Используется инфраструктурными инструментами для мониторинга доступности.
"""
# api/routes/health.py
from fastapi import APIRouter


router = APIRouter(tags=["Health"])


@router.get(
    "/health",
    summary="Проверка работоспособности сервиса (Health Check)",
    response_description="Успешный статус сервиса и его идентификатор"
)
async def health_check():
    """
    Эндпоинт проверки жизненного цикла микросервиса.

    Используется для настройки liveness/readiness проб в системах оркестрации 
    контейнеров, а также API-шлюзами для маршрутизации трафика.

    Returns:
        dict: Статический словарь с состоянием сервиса.
            - status (str): Флаг состояния, всегда "ok", если веб-сервер отвечает.
            - service (str): Уникальное имя текущего микросервиса ("balance-orchestrator").
    """
    # [ENGINEERING CONTEXT]
    # Реализация паттерна Liveness Probe:
    # Почему здесь возвращается просто статический словарь без проверки БД или GitLab?
    # Задача этого эндпоинта — просто сообщить оркестратору (K8s/Docker), что 
    # процесс Python жив, веб-сервер (Uvicorn/Gunicorn) не завис и способен 
    # обрабатывать HTTP-запросы. Если начать пинговать внешние зависимости, 
    # временный отвал GitLab приведет к рестарту всего нашего контейнера оркестратором,
    # что является антипаттерном.
    return {"status": "ok", "service": "balance-orchestrator"}
    